#!/usr/bin/env python3
"""Solve the joint angles of the two printed camera arms and print the URDF/xacro block.

Arm = clamp -> N links (200 mm pivot-to-pivot) -> head with a 25x25 post for the camera mount.
Angles are measured from vertical in the XZ plane; the head stays upright so the camera mount keeps its orientation.
  python3 gen_arms.py > ../urdf/camera_arms.xacro
"""
import numpy as np
from scipy.optimize import minimize

L = 0.200
P0 = (0.005, 0.040)           # clamp pivot relative to the table edge / table top
TZ, EDGE_X = 0.75, -0.55

def solve(n, dx, dz):
    pos = lambda a: (L * np.sum(np.sin(a)), L * np.sum(np.cos(a)))
    best = None
    for init in (np.linspace(0, 1.0, n), np.linspace(0.2, 0.8, n), np.full(n, 0.4), np.linspace(0.1, 1.3, n), np.linspace(0.6, 0.0, n)):
        r = minimize(lambda a: np.sum(np.diff(np.r_[0, a]) ** 2) + 0.3 * np.sum(np.asarray(a) ** 2), init, method="SLSQP", bounds=[(np.radians(-30), np.radians(80))] * n,
                     constraints={"type": "eq", "fun": lambda a: np.array(pos(a)) - [dx, dz]})
        if r.success and (best is None or r.fun < best.fun):
            best = r
    return best.x

def block(arm, y, n, head_xz):
    dx, dz = head_xz[0] - (EDGE_X + P0[0]), head_xz[1] - (TZ + P0[1])
    a = solve(n, dx, dz)
    th = a - np.pi / 2
    out = [f"  <!-- {arm}: clamp + {n} links + head; link angles from vertical (deg): {', '.join(f'{x:.1f}' for x in np.degrees(a))} -->",
           f'  <xacro:printed_part name="{arm}_clamp" mesh="arm_clamp.stl" parent="world" xyz="{EDGE_X} {y} {TZ}" rpy="0 0 0"/>']
    prev, prev_th = f"{arm}_clamp", 0.0
    for i in range(n):
        xyz = f"{P0[0]} 0 {P0[1]}" if i == 0 else f"{L} 0 0"
        rel = th[i] - (0.0 if i == 0 else th[i - 1])
        out.append(f'  <xacro:printed_part name="{arm}_link{i}" mesh="arm_link.stl" parent="{prev}" xyz="{xyz}" rpy="0 {rel:.6f} 0"/>')
        prev = f"{arm}_link{i}"
    out.append(f'  <xacro:printed_part name="{arm}_head" mesh="arm_head.stl" parent="{prev}" xyz="{L} 0 0" rpy="0 {-th[-1]:.6f} 0"/>')
    return out

c2x, c2z = -0.05, TZ + 0.02 + 0.80
c1x = -0.30
c1z = TZ + 0.05 + (-0.05 - (-0.5688 + 0.05084)) * np.tan(np.radians(35)) + 0.08
lines = ["<?xml version=\"1.0\"?>", '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">', "  <!-- generated by cad/gen_arms.py -->"]
lines += block("arm2", 0.0, 5, (c2x - 0.0583 - 0.03, c2z + 0.07))
lines += block("arm1", -0.18, 3, (c1x - 0.0708, c1z + 0.04))
lines.append("</robot>")
print("\n".join(lines))
